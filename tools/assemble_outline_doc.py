def main() -> int:
    html = sys.argv[1] if len(sys.argv[1:]) >= 1 else DEFAULT_HTML
    out_md = sys.argv[2] if len(sys.argv[1:]) >= 2 else DEFAULT_OUT
    subprocess.run(
        [sys.executable, os.path.join(ROOT, "tools", "report_outline.py"), html, "--md", TMP_MD],
        check=True, cwd=ROOT,
    )
    generated = open(TMP_MD, encoding="utf-8").read()

    # 机器产物切段
    def grab(title: str) -> str:
        pat = re.compile(r"^## " + re.escape(title) + r"\n(.*?)(?=^## |\Z)", re.M | re.S)
        m = pat.search(generated)
        if not m:
            raise SystemExit(f"未找到机器产物段落：{title}")
        return m.group(1).strip("\n")

    outline = grab("六、大纲（栏目 → 子栏）")
    rate = grab("一、各栏目跨栏重复数字率")
    pairs = grab("二、栏目两两对照（A 栏事实中出现在 B 栏的比例 ≥15%）")
    sub_pairs = grab("三、重复子栏（跨栏，事实重叠 ≥50% 且共享 ≥3 个事实）")
    row_pairs = grab("四、重复行（跨栏，同子栏逐行对照）")
    inner = grab("五、栏内重复（同一栏目里重复出现的标题 / 长句）")

    body = "\n".join([
        HEADER.rstrip("\n"),
        "",
        "## 二、大纲（栏目 → 子栏）",
        "",
        outline,
        "",
        "## 三、跨栏重复率实测",
        "",
        "### 3.1 各栏目跨栏重复数字率",
        "",
        rate,
        "",
        "### 3.2 栏目两两对照（A 栏事实中出现在 B 栏的比例 ≥15%）",
        "",
        pairs,
        "",
        "### 3.3 重复子栏（跨栏，事实重叠 ≥50% 且共享 ≥3 个事实）",
        "",
        sub_pairs,
        "",
        "### 3.4 重复行（跨栏，同子栏逐行对照，文本相似度 ≥70%）",
        "",
        row_pairs,
        "",
        "### 3.5 栏内重复（同一栏目里重复出现的标题 / 长句）",
        "",
        inner,
        "",
        MERGE_SECTION.rstrip("\n"),
        "",
        UNMERGED_SECTION.rstrip("\n"),
        "",
    ])
    with open(out_md, "w", encoding="utf-8") as fh:
        fh.write(body)
    print(f"✅ 已拼装 {out_md}（{len(body.splitlines())} 行）")
