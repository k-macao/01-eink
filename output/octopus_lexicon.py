# ------------------------------------------------------------------
# 确定性选池（与 octopus_ren 同口径：crc32(种子) % 池长）
# ------------------------------------------------------------------
def _pick(options, seed):
    if not options:
        return ""
    return options[zlib.crc32(str(seed).encode("utf-8")) % len(options)]


def term(name):
    """取单个词条（含 说明/市场映射/触发条件/点缀短语/分析）。"""
    return LEXICON.get(str(name))


def all_terms():
    """全部词条（list），顺序即词库定义顺序。"""
    return list(LEXICON.values())


def by_category(cat):
    """按类别取词条（list）。"""
    return [e for e in LEXICON.values() if e["cat"] == cat]


