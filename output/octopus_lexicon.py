def _vol_band(vol_pct):
    """波动分位 → 高/中/低（vol_pct 为 0~1 的扩张分位；缺失给 mid）。"""
    try:
        v = float(vol_pct)
    except (TypeError, ValueError):
        return "mid"
    if v >= 0.7:
        return "high"
    if v <= 0.3:
        return "low"
    return "mid"


def _strength(label_dir, p_pct):
    """方向 + 概率 → strong / mild（概率离 50% 越远越强；缺失给 mild）。"""
    try:
        p = float(p_pct)
    except (TypeError, ValueError):
        return "mild"
    if label_dir == "flat":
        return "strong" if abs(p - 50) < 3 else "mild"   # 中性里越接近 50 越「统货」
    return "strong" if abs(p - 50) >= 15 else "mild"


