# 活鲜度：数据新鲜度 → 等级（条件驱动，绝不冒充）
# ------------------------------------------------------------------
def freshness_grade(*, available=True, is_today=False, lag_days=None):
    """数据新鲜度 → 活鲜度等级词（活鲜 / 冰鲜 / 冻鲜 / 断气）。

    · 不可用 / 抓取失败            → 断气
    · 可用且当天（is_today）       → 活鲜
    · 可用、滞后 ≥3 个交易日       → 冻鲜
    · 可用、滞后 1~2 个交易日      → 冰鲜
    · 可用但新鲜度未知（无 is_today / 无滞后天数）→ 冰鲜（保守，绝不冒充活鲜）
    """
    if not available:
        return GRADE_DEAD
    if is_today:
        return GRADE_LIVE
    try:
        lag = int(lag_days) if lag_days is not None else None
    except (TypeError, ValueError):
        lag = None
    if lag is None:
        return GRADE_ICED
    if lag >= 3:
        return GRADE_FROZEN
    if lag >= 1:
        return GRADE_ICED
    return GRADE_LIVE


