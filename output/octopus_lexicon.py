# 方向定调：兼容「偏多/偏空/中性」「up/down/neutral」「▲ 看涨 · P(7日涨) 56%」
# 「中性（略偏涨）」等多种写法——子串命中即可，认不出就返回 None（绝不瞎猜方向）。
_DIR_UP_WORDS = ("偏多", "看涨", "看多", "多头", "略偏涨", "偏涨")
_DIR_DOWN_WORDS = ("偏空", "看跌", "看空", "空头", "略偏跌", "偏跌")
_DIR_FLAT_WORDS = ("中性", "五五开", "观望", "持平")


def _norm_dir(label):
    """方向文案 → 'up' / 'down' / 'flat' / None（None = 认不出，不点缀方向）。"""
    s = str(label or "").strip()
    if not s:
        return None
    low = s.lower()
    if low in ("up", "bullish"):
        return "up"
    if low in ("down", "bearish"):
        return "down"
    if low in ("flat", "neutral"):
        return "flat"
    # 「中性（略偏涨）」这类先判中性档（档位优先于括注里的轻微倾向）
    if any(w in s for w in _DIR_FLAT_WORDS):
        return "flat"
    if any(w in s for w in _DIR_UP_WORDS):
        return "up"
    if any(w in s for w in _DIR_DOWN_WORDS):
        return "down"
    return None


